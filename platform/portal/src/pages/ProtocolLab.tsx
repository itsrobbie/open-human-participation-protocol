import { useEffect, useState } from 'react'
import { ensureFreshToken } from '../auth/token'
import { api } from '../api/client'

type RequestType = 'Select' | 'Multiselect' | 'Text' | 'Number' | 'Date' | 'DateTime' | 'Signature'

interface LabStatus {
  status: string
  selectedOption: string | null
  selectedOptions: string[] | null
  value: string | null
  attestation: unknown | null
}

const LAB_APP_ID = 'protocol-lab.dev.test'
const requestTypes: RequestType[] = ['Select', 'Multiselect', 'Text', 'Number', 'Date', 'DateTime', 'Signature']

async function portalFetch(path: string, init?: RequestInit) {
  const token = await ensureFreshToken()
  const response = await fetch(path, {
    ...init,
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${token}`,
      ...init?.headers,
    },
  })
  if (!response.ok) {
    const text = await response.text()
    throw new Error(text || `HTTP ${response.status}`)
  }
  return response.json()
}

function createPreset(type: RequestType, userId: string) {
  const options = [
    { key: 'approve', label: 'Approve' },
    { key: 'decline', label: 'Decline' },
    { key: 'review', label: 'Review later' },
  ]
  return JSON.stringify({
    id: `protocol-lab-${Date.now()}`,
    version: '1.0',
    requester: { appId: LAB_APP_ID },
    validation: { userId },
    action: {
      summary: `Protocol Lab ${type} request`,
      description: `Custom ${type} request generated by the OHPP Protocol Lab.`,
      rationale: 'Exercise the complete requester, Resolver, and portal response path.',
      category: 'protocol-lab',
    },
    type,
    ...(type === 'Select' || type === 'Multiselect' ? { options } : {}),
    ...(type === 'Text' ? { placeholder: 'Enter a value', masked: false, keyboard: 'text' } : {}),
    ...(type === 'Number' ? { placeholder: 'Enter a number', keyboard: 'numeric', inputValidation: { required: true, min: 0, max: 100000 } } : {}),
    ...(type === 'Date' ? { keyboard: 'date' } : {}),
    ...(type === 'DateTime' ? { keyboard: 'datetime' } : {}),
    createdAt: new Date().toISOString(),
    expiry: new Date(Date.now() + 15 * 60 * 1000).toISOString(),
  }, null, 2)
}

export function ProtocolLab() {
  const [userId, setUserId] = useState('')
  const [type, setType] = useState<RequestType>('Select')
  const [payload, setPayload] = useState('')
  const [lastRequest, setLastRequest] = useState<{ id: string } | null>(() => {
    const stored = localStorage.getItem('ohpp_lab_last_request')
    return stored ? JSON.parse(stored) : null
  })
  const [status, setStatus] = useState<LabStatus | null>(null)
  const [message, setMessage] = useState('')
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(true)
  const [registered, setRegistered] = useState(false)
  const [registering, setRegistering] = useState(false)
  const [needsBrowserDevice, setNeedsBrowserDevice] = useState(false)

  useEffect(() => {
    void (async () => {
      try {
        const [profile, devices, labStatus] = await Promise.all([
          portalFetch('/api/users/me', { method: 'POST' }),
          api.getDevices(),
          portalFetch('/api/protocol-lab/status'),
        ])
        setUserId(profile.id)
        setNeedsBrowserDevice(!devices.some((device) => device.isActive))
        setRegistered(labStatus.registered)
        if (labStatus.registered) {
          setPayload(createPreset('Select', profile.id))
        }
      } catch (err) {
        setError(err instanceof Error ? err.message : 'Could not load protocol lab')
      } finally {
        setLoading(false)
      }
    })()
  }, [])

  useEffect(() => {
    if (registered && userId && !payload) setPayload(createPreset(type, userId))
  }, [registered, userId, type, payload])

  useEffect(() => {
    if (!lastRequest) return
    const timer = window.setInterval(() => {
      void portalFetch(`/api/protocol-lab/requests/${lastRequest.id}/status`)
        .then(setStatus)
        .catch(() => undefined)
    }, 1500)
    return () => window.clearInterval(timer)
  }, [lastRequest])

  const registerLab = async () => {
    setRegistering(true)
    setError('')
    setMessage('')
    try {
      await portalFetch('/api/protocol-lab/register', { method: 'POST' })
      setRegistered(true)
      setPayload(createPreset(type, userId))
      setMessage('Protocol Lab registered successfully. You can now send requests.')
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not register Protocol Lab')
    } finally {
      setRegistering(false)
    }
  }

  const sendRequest = async () => {
    setError('')
    setMessage('')
    try {
      JSON.parse(payload)
      const result = await portalFetch('/api/protocol-lab/requests', {
        method: 'POST',
        body: JSON.stringify({ payload }),
      })
      setLastRequest({ id: result.requestId })
      localStorage.setItem('ohpp_lab_last_request', JSON.stringify({ id: result.requestId }))
      setStatus({ status: 'pending', selectedOption: null, selectedOptions: null, value: null, attestation: null })
      setMessage(`Request sent over HTTP. Request ID: ${result.requestId}`)
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not send request')
    }
  }

  const enableBrowserApprovals = async () => {
    try {
      await api.createDevice('Protocol Lab browser', 'browser')
      setNeedsBrowserDevice(false)
      setMessage('Browser approvals enabled for the Protocol Lab.')
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not enable browser approvals')
    }
  }

  if (loading) return <p>Loading Protocol Lab...</p>

  return (
    <div data-testid="protocol-lab" className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold">Protocol Lab</h1>
        <p className="text-sm text-gray-600 dark:text-slate-400 mt-2">
          The Protocol Lab is a self-contained Requester app (<code>{LAB_APP_ID}</code>) that registers with the Resolver through the real ceremony, then sends requests using its own identity and token.
        </p>
      </div>

      {needsBrowserDevice && (
        <div className="bg-indigo-50 dark:bg-indigo-900/20 border border-indigo-200 dark:border-indigo-700 rounded-lg p-4 text-sm">
          <p className="font-medium">Enable browser approvals</p>
          <p className="mt-1">The Resolver requires an active approval device before it accepts requests.</p>
          <button data-testid="ohpp.protocollab.enable-approvals" onClick={() => void enableBrowserApprovals()} className="mt-3 px-4 py-2 bg-indigo-600 text-white rounded text-sm">Enable browser approvals</button>
        </div>
      )}

      {!registered && !needsBrowserDevice && (
        <div className="bg-yellow-50 dark:bg-yellow-900/20 border border-yellow-200 dark:border-yellow-700 rounded-lg p-4 text-sm">
          <p className="font-medium">Register the Protocol Lab</p>
          <p className="mt-1">
            The Lab must register itself as a Requester app with the Resolver through the standard registration ceremony before it can send requests.
          </p>
          <button
            data-testid="register-lab"
            onClick={() => void registerLab()}
            disabled={registering}
            className="mt-3 px-4 py-2 bg-indigo-600 text-white rounded text-sm disabled:opacity-50"
          >
            {registering ? 'Registering...' : 'Register Protocol Lab'}
          </button>
        </div>
      )}

      {registered && (
        <section className="bg-white dark:bg-slate-800 rounded-lg p-5 border border-gray-200 dark:border-slate-700 space-y-4">
          <h2 className="font-semibold">1. Compose and send</h2>
          <div className="grid sm:grid-cols-2 gap-4">
            <div className="text-sm">
              <p className="font-medium">Requester identity</p>
              <p className="text-gray-600 dark:text-slate-400 mt-1"><code>{LAB_APP_ID}</code></p>
            </div>
            <label className="text-sm">Request type
              <select data-testid="ohpp.protocollab.request-type" aria-label="Request type" value={type} onChange={(event) => {
                const nextType = event.target.value as RequestType
                setType(nextType)
                setPayload(createPreset(nextType, userId))
              }} className="mt-1 w-full border rounded px-3 py-2 dark:bg-slate-700">
                {requestTypes.map((requestType) => <option key={requestType}>{requestType}</option>)}
              </select>
            </label>
          </div>
          <label className="text-sm block">Protocol JSON
            <textarea data-testid="protocol-payload" aria-label="Protocol JSON" value={payload} onChange={(event) => setPayload(event.target.value)} rows={18} className="mt-1 w-full border rounded px-3 py-2 font-mono text-xs dark:bg-slate-700" />
          </label>
          <div className="flex gap-3">
            <button onClick={() => setPayload(createPreset(type, userId))} className="px-4 py-2 border rounded text-sm">Load {type} preset</button>
            <button onClick={() => void sendRequest()} disabled={!payload} className="px-4 py-2 bg-indigo-600 text-white rounded text-sm disabled:opacity-50">Send over protocol</button>
          </div>
        </section>
      )}

      {message && <div className="bg-green-50 border border-green-200 text-green-800 rounded p-3 text-sm" role="status">{message}</div>}
      {error && <div className="bg-red-50 border border-red-200 text-red-800 rounded p-3 text-sm" role="alert">{error}</div>}

      {lastRequest && status && (
        <section className="bg-white dark:bg-slate-800 rounded-lg p-5 border border-gray-200 dark:border-slate-700" data-testid="protocol-status">
          <h2 className="font-semibold">Requester SDK status</h2>
          <p className="text-sm mt-2"><span data-testid="protocol-request-id">{lastRequest.id}</span>: <strong>{status.status}</strong></p>
          {status.selectedOption && <p className="text-sm mt-1">selectedOption: <code>{status.selectedOption}</code></p>}
          {status.selectedOptions && <p className="text-sm mt-1">selectedOptions: <code>{status.selectedOptions.join(', ')}</code></p>}
          {status.value && <p className="text-sm mt-1">value: <code>{status.value}</code></p>}
          {status.attestation ? (
            <details className="mt-4" open>
              <summary className="text-sm font-medium cursor-pointer">Signed attestation envelope</summary>
              <pre data-testid="protocol-attestation" className="mt-2 overflow-x-auto rounded bg-slate-950 p-4 text-xs text-slate-100">{JSON.stringify(status.attestation, null, 2)}</pre>
            </details>
          ) : (
            <div className="mt-3 text-sm text-gray-600 dark:text-slate-400">
              <p>Waiting for resolution. Respond on the <a href="/pending" className="text-indigo-600 dark:text-indigo-400 underline font-medium">Pending page</a>.</p>
            </div>
          )}
        </section>
      )}
    </div>
  )
}
